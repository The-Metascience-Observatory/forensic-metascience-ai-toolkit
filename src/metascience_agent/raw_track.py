"""The raw-data track: `copy_paste_detector` over a paper's spreadsheets.

The `raw_data` module (modules/raw_data/MODULE.md) runs this file as a CHILD
PROCESS (`python -m metascience_agent.raw_track PAPER_DIR`), so a scan that
runs long can be killed without taking the review with it, the same posture
as the image and text tracks. It calls no model.

Its rows are QUARANTINED signals, never findings of record:

- Row-pair evidence has no chance model (CLAUDE.md, "Duplication counts
  groups, pairs and rows separately"), so a fired group is a lead, not a
  probability. MEASURED 2026-10-15 on three fixture spreadsheets: 2,088
  accusatory row-pair groups, almost all from model-generated tables (a
  cost-effectiveness workbook repeats its inputs by design).
- One row per (file, kind), never one per group, for the same reason: a
  thousand rows is not a review.
- Groups, row pairs and rows stay separate counts in `inputs`.

`rows_v2` turns the detector's result into findings_v2 rows; the module
merges them like the text track's.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

#: Structured formats the detector reads (`copy_paste_detector.paper.FORMATS`).
FORMATS = (".csv", ".tsv", ".xlsx", ".xlsm")

#: Subdirectories a fetcher may put supplements in. An ALLOWLIST, never a
#: walk: review output, caches and panel crops live under the paper too.
SUPPLEMENT_SUBDIRS = ("supplementary", "supplements", "supplement", "si", "data")

QUARANTINE_REASON = (
    "raw-data copy-paste detector: an unreviewed deterministic signal. "
    "Row-pair matches have no chance model, and tables generated by a model "
    "or a simulation repeat values by design; read the cells before "
    "treating this as evidence")


def structured_files(paper_dir: str | Path) -> list[Path]:
    """The paper's spreadsheets and CSVs: top level plus the allowlisted
    supplement folders, sorted, hidden files excluded."""
    base = Path(paper_dir)
    found: list[Path] = []
    for folder in (base, *(base / d for d in SUPPLEMENT_SUBDIRS)):
        if not folder.is_dir():
            continue
        for p in sorted(folder.iterdir()):
            if p.is_file() and p.suffix.lower() in FORMATS \
                    and not p.name.startswith((".", "~$")):
                found.append(p)
    # fetchpdf's linked deposits (`<stem>_data_artifacts/<deposit>/`), through
    # the same scan the source resolver uses so the two agree.
    from .supplements import data_artifact_files

    seen = set(found)
    found += [p for p in data_artifact_files(base)[0]
              if p.suffix.lower() in FORMATS and p not in seen]
    return found


def scan(paper_dir: str | Path) -> dict:
    """Run the detector over every structured file in the paper.

    `{"files": [], ...}` with no detector result when there is nothing to
    read: that is "did not run", not "found nothing".
    """
    from copy_paste_detector.paper import detect_paper_duplication
    from copy_paste_detector.readers import DetectionLimits

    base = Path(paper_dir)
    files = structured_files(base)
    out: dict = {"files": [str(p.relative_to(base)) for p in files]}
    if not files:
        return out
    # The per-file CLI's bounded defaults (5,000 rows, 100 columns, 8 sheets,
    # 5,000 row pairs): a partial scan says so in its coverage.
    result = detect_paper_duplication(
        [{"path": str(p), "name": str(p.relative_to(base))} for p in files],
        paper_id=base.name, limits=DetectionLimits(5000, 100, 8),
        max_row_pairs=5000)
    result.pop("evidence_tables", None)          # cell context; not needed here
    out["result"] = result
    return out


def _files_of(group: dict) -> list[str]:
    refs = (group.get("cells") or []) + (group.get("cells_a") or []) \
        + (group.get("cells_b") or [])
    names = sorted({str(r.get("file")) for r in refs if r.get("file")})
    return names or ["(file not recorded)"]


def rows_v2(scan_out: dict, paper_dir: str | Path) -> list[dict]:
    """findings_v2 rows: one per (file, kind) with an accusatory group."""
    from . import findings_v2, severity9
    from .tools.severity import ACCUSES_AT_ALL

    result = (scan_out or {}).get("result") or {}
    buckets: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for g in result.get("duplicate_groups") or []:
        if g.get("severity") not in ACCUSES_AT_ALL:
            continue
        for name in _files_of(g):
            buckets[(name, str(g.get("kind") or "duplicate"))].append(g)

    rows: list[dict] = []
    for (name, kind), groups in sorted(buckets.items()):
        # Duplication is improbable, never impossible (rulebook 3, 9, 11):
        # whatever a group says, the row's grade stops at highly_suspicious.
        worst = ("highly_suspicious"
                 if any(g.get("severity") != "suspicious" for g in groups)
                 else "suspicious")
        n_high = sum(g.get("severity") == "highly_suspicious" for g in groups)
        label = kind.replace("_", " ")
        inputs = {
            "file": name,
            "kind": kind,
            "n_groups_flagged": len(groups),
            "n_groups_highly_suspicious": n_high,
            "n_groups_suspicious": len(groups) - n_high,
            "example_group_ids": [g.get("id") for g in groups[:5]],
            # Paper-wide, across every file: groups, pairs and rows are
            # different counts and are never folded into one.
            "paper_n_row_pair_groups": result.get("n_row_pair_groups"),
            "paper_n_row_pairs": result.get("n_row_pairs"),
            "paper_n_rows_implicated": result.get("n_rows_implicated"),
            "paper_n_rows_total": result.get("n_rows_total"),
            "coverage": (result.get("coverage") or {}).get("status"),
        }
        rows.append({
            "slug": f"raw_{kind}_{len(rows) + 1}",
            "producer": "raw_data_track",
            "technique": "detect_raw_duplication",
            "title": findings_v2.clip(
                f"{name}: {len(groups)} {label} group(s) flagged by the "
                "copy-paste detector", 90),
            "description": findings_v2.clip(
                f"The raw-data detector flagged {len(groups)} {label} "
                f"group(s) in {name} ({n_high} highly suspicious). "
                + str(result.get("explanation") or ""), 700),
            "location": name,
            "outcome": "problem",
            "provisional_severity": severity9.FIVE_TO_NINE[worst],
            "severity_is_provisional": True,
            "impossible": False,
            "quarantined": True,
            "quarantine_reason": QUARANTINE_REASON,
            "computed_by": "deterministic_track",
            "tool_verdict": {
                "severity": "indeterminate",
                "tool": "detect_raw_duplication",
                "validated": True,
                "quarantined_raw": worst,
            },
            "inputs": inputs,
            "anchors": [],
            "reproduction": "metascience tool run detect_raw_duplication "
                            "--json " + json.dumps(json.dumps({"path": name})),
        })
    findings_v2.assign_finding_ids(rows, Path(paper_dir).name)
    findings_v2.clamp_provisionals(rows)          # QUARANTINE_CAP
    return rows


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print("usage: python -m metascience_agent.raw_track PAPER_DIR",
              file=sys.stderr)
        return 2
    sys.stdout.write(json.dumps(scan(args[0]), default=str,
                                allow_nan=False) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

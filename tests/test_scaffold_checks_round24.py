class TestAVerdictMayOnlyWithdraw:
    """Over the cross-product of (what the free path decides) x (what a model
    answers), a verdict never makes the licence MORE permissive.

    THE CROSS-PRODUCT IS THE POINT. A test that only shows `true` withdrawing
    would pass on an implementation where `false` GRANTS, which is the exact
    inversion D71 forbids and which this module's name makes easy to write by
    accident.
    """

    SENTENCES = {
        "the free path licenses it (honest)": ("var:reed", REED_G),
        "the free path licenses it (leak)": ("var:warp", None),
        "the free path refuses it (unattributable)":
            ("var:warp", UNRESOLVED),
        "the free path refuses it (says nothing)":
            ("var:warp", f"{HALF}."),
    }

    def _rec(self, label, answers):
        vid, sentence = self.SENTENCES[label]
        acc, text = mill(sentence if sentence is not None
                         else LEAKS["leading adjunct naming a rival"])
        return verification(evaluate(acc, text, answers=answers)["account"], vid)

    @pytest.mark.parametrize("label", sorted(SENTENCES))
    def test_a_keeping_verdict_changes_nothing(self, label):
        free = self._rec(label, None)
        said_no = self._rec(label, ALL_KEEP)
        for field in ("establishes_step_of_one", "discreteness_source",
                      "kind_makes_it_necessary"):
            assert said_no[field] == free[field], field
        assert said_no["discreteness_licence_withdrawn_by_model"] is False

    @pytest.mark.parametrize("label", sorted(SENTENCES))
    def test_a_withdrawing_verdict_is_never_more_permissive(self, label):
        free = self._rec(label, None)
        said_yes = self._rec(label, ALL_WITHDRAW)
        assert not (said_yes["establishes_step_of_one"]
                    and not free["establishes_step_of_one"])
        assert not (said_yes["discreteness_source"] == premises.STATED_DISCRETENESS
                    and free["discreteness_source"] != premises.STATED_DISCRETENESS)

    @pytest.mark.parametrize("label", sorted(SENTENCES))
    def test_no_verdict_of_either_sign_adds_a_check(self, label):
        """The question the brief asks of this build: can it make a check RUN
        that would not have run before? Measured on the rows, not argued."""
        vid, sentence = self.SENTENCES[label]
        acc, text = mill(sentence if sentence is not None
                         else LEAKS["leading adjunct naming a rival"])
        free = evaluate(acc, text, answers=None)
        for answers in (ALL_KEEP, ALL_WITHDRAW):
            got = evaluate(acc, text, answers=answers)
            assert set(got["granularity_rows"]) <= set(free["granularity_rows"])
            assert set(got["accusations"]) <= set(free["accusations"])

    def test_a_verdict_cannot_restore_a_licence_the_free_path_withheld(self):
        """The named inversion, asserted on its own because it is the one a
        future edit is most likely to introduce: the KEEPING answer must not
        mean `grant`. Asserted over both answers, so it holds whichever of them
        `WITHDRAWN_ON_FALSE` makes the withdrawing one."""
        acc, text = mill(UNRESOLVED)
        free = verification(evaluate(acc, text, answers=None)["account"], "var:warp")
        assert free["establishes_step_of_one"] is False
        for answers in (ALL_KEEP, ALL_WITHDRAW):
            rec = verification(evaluate(acc, text, answers=answers)["account"],
                               "var:warp")
            assert rec["establishes_step_of_one"] is False
            assert rec["discreteness_source"] == premises.ASSUMED_DISCRETENESS



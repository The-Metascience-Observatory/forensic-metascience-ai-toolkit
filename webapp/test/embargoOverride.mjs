import assert from 'node:assert/strict';
import { OVERRIDE_PHRASE, overrideConfirmed, overrideLine } from '../lib/embargoOverride.ts';
assert.equal(OVERRIDE_PHRASE, 'OVERRIDE EMBARGO');
assert.equal(overrideConfirmed('OVERRIDE EMBARGO'), true);
assert.equal(overrideConfirmed('  OVERRIDE EMBARGO '), true);
for (const bad of ['', 'override embargo', 'OVERRIDE', 'yes', 'true', null, undefined]) assert.equal(overrideConfirmed(bad), false, String(bad));
const line = overrideLine({project:'p', dir:'d', doi:'10.1/x', website_id:'x-2025', marker:'/c/EMBARGO.json'}, new Date('2026-10-22T12:00:00Z'));
assert.ok(line.endsWith('\n'));
assert.deepEqual(JSON.parse(line), {at:'2026-10-22T12:00:00.000Z', action:'website_publication', project:'p', dir:'d', doi:'10.1/x', website_id:'x-2025', marker:'/c/EMBARGO.json', confirmed_phrase:'OVERRIDE EMBARGO'});
console.log('embargo override: phrase must be typed exactly; one JSON audit line per override');

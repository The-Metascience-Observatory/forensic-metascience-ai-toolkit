"""An account-level refusal is not a per-paper failure.

MEASURED 2026-08-23: a grok batch with an exhausted xAI balance produced twenty
identical `402 Payment Required` errors across ten papers, ten full tracebacks,
and ten rows in `failed.jsonl` naming papers that were never analysed. Batch
cost was $0.00 -- the API refused before billing -- so the whole cascade was
noise generated by our own error handling.

The invariant these tests pin is the one CLAUDE.md already states for
`PreflightError`: an environment fault stops the batch once and stays OUT of the
retry queue, because retrying cannot install a library or add credit.
"""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

import pytest


from metascience_agent.llm_backend import (            # noqa: E402
    BackendUnavailable, FATAL_BACKEND_MARKERS, fatal_backend_reason,
)

#: Verbatim from the failed run.
REAL_402 = (
    'Error: Internal error: {\n  "message": "API error (status 402 Payment '
    'Required): Grok Build usage balance exhausted",\n  "http_status": 402\n}\n'
)


class TestClassification:
    def test_the_real_402_is_fatal(self):
        assert fatal_backend_reason(REAL_402) == "402"

    @pytest.mark.parametrize("stderr", [
        "Not logged in · Please run /login",
        "API error (status 401): Unauthorized",
        "Your credit balance is too low",
        "insufficient_quota",
        "Error: invalid api key",
        # Codex phrasings. The first is the measured logged-out stderr
        # (2026-09-01): the websocket 401 hits the "401" marker.
        "ERROR codex_api: failed to connect to websocket: HTTP error: "
        "401 Unauthorized, url: wss://api.openai.com/v1/responses",
        "To get started, run codex login",
        "Usage limit reached for your plan",
    ])
    def test_other_account_refusals_are_fatal(self, stderr):
        assert fatal_backend_reason(stderr) is not None

    @pytest.mark.parametrize("stderr", [
        "API error (status 429): rate limit exceeded, retry after 30s",
        "HTTP 500 Internal Server Error",
        "HTTP 503 Service Unavailable",
        "stream timed out after 1800s",
        "connection reset by peer",
        "",
    ])
    def test_transient_failures_stay_retryable(self, stderr):
        """THE REGRESSION THAT WOULD HURT MOST. A rate limit or a 5xx is
        transient; classifying one as fatal would stop a healthy overnight
        batch on a hiccup, which is worse than the cascade being fixed."""
        assert fatal_backend_reason(stderr) is None

    def test_a_429_is_not_matched_by_the_402_marker(self):
        """Substring matching on bare status codes is the obvious way to get
        this wrong."""
        assert fatal_backend_reason("status 429 too many requests") is None
        assert "429" not in FATAL_BACKEND_MARKERS

    def test_matching_is_case_insensitive(self):
        assert fatal_backend_reason("PAYMENT REQUIRED") is not None


class TestBatchHandling:
    def test_the_environment_fault_tuple_includes_it(self):
        """`batch_analyze` already stops and skips the retry queue for
        PreflightError and BudgetUnsupported; this only had to reach them."""
        src = (Path(__file__).resolve().parents[1]
               / "src" / "metascience_agent" / "batch.py").read_text()
        line = next(l for l in src.splitlines()
                    if "except (PreflightError" in l)
        assert "BackendUnavailable" in line

    def test_probe_fails_open_when_the_cli_is_missing(self, monkeypatch):
        """The probe converts a refusal into one line. It must never become a
        new way for a healthy run to die."""
        from metascience_agent import batch as B
        monkeypatch.setattr(B.shutil, "which", lambda _n: None)
        assert asyncio.run(B.probe_backend("grok")) is None

    def test_probe_fails_open_on_a_crash(self, monkeypatch):
        from metascience_agent import batch as B
        monkeypatch.setattr(B.shutil, "which", lambda _n: "/bin/true")

        async def boom(*a, **k):
            raise OSError("no subprocess for you")

        monkeypatch.setattr(B.asyncio, "create_subprocess_exec", boom)
        assert asyncio.run(B.probe_backend("grok")) is None

    def test_probe_reports_the_reason_when_the_account_refuses(self, monkeypatch):
        from metascience_agent import batch as B
        monkeypatch.setattr(B.shutil, "which", lambda _n: "/bin/true")

        class _P:
            async def communicate(self, _stdin):
                return REAL_402.encode(), b""

        async def fake(*a, **k):
            return _P()

        monkeypatch.setattr(B.asyncio, "create_subprocess_exec", fake)
        assert asyncio.run(B.probe_backend("grok")) == "402"

    def test_probe_uses_each_cli_s_own_print_mode(self, monkeypatch):
        """grok takes the prompt as the VALUE of `--single`; passing it as a
        separate argv entry makes it exit with "a value is required for
        '--single'", which carries no fatal marker -- so the probe failed open
        and the batch ran anyway. That happened on the first attempt."""
        from metascience_agent import batch as B
        monkeypatch.setattr(B.shutil, "which", lambda n: f"/usr/bin/{n}")
        seen = {}

        class _P:
            async def communicate(self, _stdin):
                return b"ok", b""

        async def fake(*argv, **k):
            seen["argv"] = list(argv)
            return _P()

        monkeypatch.setattr(B.asyncio, "create_subprocess_exec", fake)
        asyncio.run(B.probe_backend("grok"))
        assert "--single" in seen["argv"]
        assert seen["argv"][seen["argv"].index("--single") + 1] == "ping"
        asyncio.run(B.probe_backend("claude"))
        assert "-p" in seen["argv"] and "--single" not in seen["argv"]
        # Codex: `exec` with the explicit stdin sentinel, isolated from the
        # user's config and any git repo, read-only, ephemeral, low effort --
        # a real tiny spend, because only a spend attempt surfaces an
        # exhausted balance.
        asyncio.run(B.probe_backend("codex"))
        assert seen["argv"][1] == "exec"
        assert seen["argv"][-1] == "-"
        for flag in ("--ignore-user-config", "--skip-git-repo-check",
                     "--ephemeral"):
            assert flag in seen["argv"]
        assert 'model_reasoning_effort="low"' in seen["argv"]


class TestPreflight:
    def test_reachability_is_optional_and_makes_no_call(self):
        """Preflight's fatal checks are local and free by design. A billable
        round trip on every `_run_stage` would change what the command is for,
        so the live probe lives in `batch`, at the point of spend."""
        from metascience_agent.preflight import backend_reachable_row
        name, good, detail = backend_reachable_row("grok")
        assert good is True, "the row must never block a run"
        assert "grok" in name
        assert "batch" in detail

    def test_assert_ready_does_not_consult_it(self):
        from metascience_agent import preflight
        names = [n for n, _g, _d in preflight.fatal_checks(refresh=True)]
        assert not any("reachable" in n for n in names)

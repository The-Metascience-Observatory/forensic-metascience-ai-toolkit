class TestTheQuestionAsksThePremise:
    """SUPERSEDED AND REPLACED BY ROUND 28. This class pinned the ATTACHMENT
    wording; the question now asks the premise itself, so what is pinned is the
    property each of four inverted wordings violated.

    THE WORDING IS THE INSTRUMENT, and four premise questions in this repo have
    now shipped wrong ones -- `averaging`'s asked whether any combination
    happened, `varying_n`'s offered a second anchor a paper's enrolment fills,
    round 24's first draft inverted its own polarity on a real run, and round
    28's first three widenings inverted on every run.

    THE RESULT THAT DECIDES THE SHAPE OF THIS QUESTION. Round 28 widened the
    question from attachment to the premise itself and measured four wordings
    through `adjudicate` on one two-candidate paper: a "does it fall short"
    negation, a positive "could it be a fraction", a positive four-fact
    disjunction, and the third of those with `PREAMBLE`'s polarity rule
    neutralised. EVERY ONE returned the correct REASON with the boolean
    inverted, and round 24's own string on the SAME paper did not. The model was
    reading the passage correctly throughout and filling a field called
    `establishes` with whether the premise holds. So the question is asked in the
    direction the field is named for, and `premise_reading.WITHDRAWN_ON_FALSE`
    carries the consequence.
    """

    Q = PR.QUESTIONS[AA.PREMISE]

    def test_it_asks_the_premise_in_the_direction_the_field_is_named_for(self):
        """`establishes` means the premise holds, so TRUE must mean that."""
        assert self.Q.startswith("Does this passage show that the figure this "
                                 "paper reports for ONE SUBJECT on the target "
                                 "variable is a whole number?")
        assert PR.withdraws(AA.PREMISE, True) is False
        assert PR.withdraws(AA.PREMISE, False) is True

    def test_the_true_clause_comes_first(self):
        """Every question in the set states its TRUE condition first, and the
        two that did not are the two that inverted."""
        assert self.Q.index("Answer TRUE only where it does") \
            < self.Q.index("Answer FALSE in any of these four cases")

    def test_it_names_all_three_sub_questions_as_ways_the_passage_falls_short(self):
        """The widening is the point: one question, three channels. Attachment
        is (a), polarity is (b), unit of observation is (c)."""
        assert "describes some OTHER quantity" in self.Q
        assert "granularity finer than whole numbers" in self.Q
        assert "attached to a single OBSERVATION of it" in self.Q

    def test_ambiguity_resolves_toward_the_refusal(self):
        """(d), and it has to be in the question because `PREAMBLE` is shared
        with the licence premises, whose instinct is the opposite."""
        assert "could equally describe the target or another quantity" in self.Q
        assert self.Q.rstrip().endswith("answer FALSE.")

    def test_it_does_not_state_the_consequence_of_a_verdict(self):
        """The preamble already tells the model a wrong `true` causes a false
        accusation. That is now the RIGHT way round for this premise -- a wrong
        `true` keeps a licence that should have fallen -- so it is left to the
        preamble and not repeated here, where repeating it would push toward
        `false` on a question whose honest arm is the larger one."""
        for word in ("accus", "check will", "removes the check", "falsely"):
            assert word not in self.Q

    def test_it_does_not_invite_an_answer_from_priors(self):
        """A model that answers "a Likert item is an integer scale" from general
        knowledge keeps a licence the passage does not support."""
        assert "do not bring in anything you know about measures of this kind" \
            in self.Q
        assert "do not answer from what is likely to be true" in self.Q

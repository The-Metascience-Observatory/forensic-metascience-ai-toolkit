"""The parallel-pipeline agent prompts: composition, boundary, examples.

Three contracts, each a named guard:
- DISJOINTNESS: science_error.md never names a tool-expert-only registry
  tool -- the scope boundary is phrased as categories, and weakening this
  test instead of fixing the prompt is how guards stop guarding.
- The embedded example JSON VALIDATES against the producer subset schema, so
  the examples cannot rot as the schema moves.
- The assemblers compose the ladder, the shared rulebook, the role addendum,
  and a role-FILTERED CLI map (a map naming tools an agent cannot call is an
  invitation to off-list calls).
"""

import json
import re
from pathlib import Path

import jsonschema
import pytest

from metascience_agent.core import prompts
from metascience_agent import registry as R

SCIENCE_MD = prompts.prompt_path("science_error.md").read_text()
TOOL_MD = prompts.tool_expert_body()   # assembled: step-3 guidance lives in TOOL.md


def _json_blocks(text):
    return [json.loads(m.group(1))
            for m in re.finditer(r"```json\n(.*?)```", text, re.S)]


class TestDisjointness:
    def test_no_tool_expert_only_registry_name_in_the_science_prompt(self):
        exclusive = set(R.stage_tools(R.TOOL_AGENT)) - set(
            R.stage_tools(R.SCIENCE_AGENT))
        offenders = sorted(n for n in exclusive if n in SCIENCE_MD)
        assert not offenders, (
            "science_error.md names tools it cannot call -- rephrase the "
            f"handoff as a CATEGORY, do not weaken this test: {offenders}")

    def test_the_guard_can_fire(self):
        """Positive control: a name the science agent DOES own appears, so an
        all-clear above is not a grep matching nothing."""
        assert "check_flow_arithmetic" in SCIENCE_MD

class TestExamplesCannotRot:
    @pytest.mark.parametrize("producer", ["tool_expert", "science_error"])
    def test_every_embedded_finding_example_validates(self, producer):
        # Finding rows only: the prompts also carry register/anatomy JSON
        # examples, which are a different schema's business.
        md = TOOL_MD if producer == "tool_expert" else SCIENCE_MD
        rows = [b for b in _json_blocks(md)
                if isinstance(b, dict) and "slug" in b and "technique" in b]
        assert rows, f"{producer}: the prompt must carry example finding JSON"
        item = prompts.producer_findings_schema(producer)[
            "properties"]["findings"]["items"]
        for row in rows:
            jsonschema.validate(row, item)

    def test_the_science_examples_cover_the_three_new_techniques(self):
        used = {b["technique"] for b in _json_blocks(SCIENCE_MD)}
        assert {"check_flow_arithmetic", "factual_claim",
                "internal_contradiction"} <= used


class TestAssemblers:
    def test_both_prompts_carry_the_ladder_and_the_role_addendum(self):
        for text in (prompts.tool_expert_system_prompt(),
                     prompts.science_error_system_prompt()):
            assert "only problem in the paper" in text  # the rubric question
            assert "Who each rule binds" in text        # rulebook_roles.md
            assert "## Severity enum" in text           # the shared rulebook

    def test_no_cli_map_the_pipeline_writes_reproductions(self):
        """Phase 3b: `reproduction` is generated by replaying the call behind a
        finding, so neither analyst is taught CLI verbs (the map was ~2.9K
        characters per prompt, and 57.6% of the commands it produced failed)."""
        for text in (prompts.tool_expert_system_prompt(),
                     prompts.science_error_system_prompt()):
            assert "CLI names for `reproduction` commands" not in text
            assert "# Reproduction commands" in text
            assert "metascience tool run" in text
            assert "-> metascience" not in text

    def test_figure_section_strips_from_the_tool_prompt(self):
        on = prompts.tool_expert_system_prompt(figures=True)
        off = prompts.tool_expert_system_prompt(figures=False)
        assert "## Figures: what the paper shows but does not print" in on
        assert "## Figures: what the paper shows but does not print" not in off

    def test_grok_route_appends_per_backend(self):
        assert "search_tool" in prompts.science_error_system_prompt(
            grok_mcp_route=True)
        assert "search_tool" not in prompts.science_error_system_prompt()


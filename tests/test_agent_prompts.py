class TestTheRCrossCheckStateIsStated:
    """MEASURED 2026-08-22 on 10.1177--0093854811403123: two findings shipped
    at severity 2 and 3 carrying "The GRIM-family R cross-check is still
    pending" and "Awaiting editorial-stage R GRIMMER cross-check".

    Both prompts require an `impossible` to be cross-checked against R and say
    an unobtainable cross-check drops the severity -- but neither says whether
    R is installed on the machine running, so the model writes about a step
    without knowing whether it can happen. Either way the wording is wrong: an
    accusation that reads as "confirmation pending" is being published now."""

    def test_both_ranking_prompts_carry_the_availability_block(self):
        from metascience_agent.core.prompts import (
            adjudication_system_prompt,
            tool_expert_system_prompt,
        )
        for name, text in (("tool_expert", tool_expert_system_prompt()),
                           ("adjudicator", adjudication_system_prompt())):
            assert "R cross-check on this machine" in text, name
            assert ("AVAILABLE" in text or "UNAVAILABLE" in text), name

    def test_both_branches_forbid_the_pending_wording(self):
        """Whichever branch this machine takes, "pending" must be ruled out."""
        from metascience_agent.core.prompts import r_crosscheck_note
        note = r_crosscheck_note()
        assert "pending" in note.lower()
        assert "await" in note.lower()

    def test_the_tool_prompt_names_the_stage_that_holds_the_tool(self):
        """It said "the editorial stage, which holds that tool". The parallel
        pipeline has no editorial stage, and `r_grim_ground_truth` is
        registered adjudicator-only -- which is how a finding came to name a
        stage that does not run."""
        from metascience_agent import registry as R
        from metascience_agent.core.prompts import tool_expert_system_prompt

        assert "r_grim_ground_truth" not in R.stage_tools(R.TOOL_AGENT)
        assert "r_grim_ground_truth" in R.stage_tools(R.ADJUDICATOR)
        flat = " ".join(tool_expert_system_prompt().split())
        assert "ADJUDICATOR, which is the stage that holds" in flat
        assert "editorial stage, which holds that tool" not in flat

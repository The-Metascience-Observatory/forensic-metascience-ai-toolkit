def _identifiers_and_literals(path: str) -> set[str]:
    """Every name, attribute and non-docstring string literal in a module.

    THE ROUND-15 RAIL SPLITS ON `\"\"\"` AND KEEPS THE TAIL, which checks only
    whatever happens to follow the LAST docstring in the file -- on a module
    whose last function is documented, that is a handful of lines. This parses
    instead, so a forbidden name cannot hide above the final docstring. Comments
    are not code and are not read.
    """
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    docs = {d for node in ast.walk(tree)
            if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                                 ast.AsyncFunctionDef))
            for d in [ast.get_docstring(node, clean=False)] if d}
    out: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            out.add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                               ast.ClassDef)):
            out.add(node.name)
        elif isinstance(node, ast.arg):
            out.add(node.arg)
        elif isinstance(node, ast.alias):
            out.add(node.asname or node.name)
        elif isinstance(node, ast.Attribute):
            out.add(node.attr)
        elif isinstance(node, ast.Constant) and isinstance(node.value, str) \
                and node.value not in docs:
            out.add(node.value)
    return out


